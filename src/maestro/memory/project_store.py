from __future__ import annotations

import json
from pathlib import Path
from typing import Any


class ProjectStore:
    """
    Append-only JSONL primitive for durable state events.

    TX is expected to be the only Council that calls `append_commit`
    after MAESTRO's constitution authorizes a durable commit.
    """

    def __init__(self, path: str | Path):
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)

    def append_commit(self, record: dict[str, Any]) -> None:
        with self.path.open("a", encoding="utf-8") as f:
            f.write(json.dumps(record, ensure_ascii=False, sort_keys=True) + "\n")

    def read_all(self) -> list[dict[str, Any]]:
        if not self.path.exists():
            return []
        return [
            json.loads(line)
            for line in self.path.read_text(encoding="utf-8").splitlines()
            if line.strip()
        ]
